-- 두리샵(상품 + 장바구니)용 표 만들기
-- Supabase 대시보드 > SQL Editor > New query 에 전부 붙여넣고 Run 하세요. (여러 번 실행해도 안전해요)

-- 1) 상품 표
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  price integer not null check (price >= 0),   -- 원 단위
  emoji text not null default '🐾',
  category text not null default '용품',
  description text,
  created_at timestamptz not null default now()
);

-- 2) 장바구니 표 (cart_id = 브라우저가 만든 장바구니 번호)
create table if not exists public.cart_items (
  id bigint generated always as identity primary key,
  cart_id text not null check (char_length(cart_id) between 8 and 64),
  product_id bigint not null references public.products(id) on delete cascade,
  quantity integer not null default 1 check (quantity between 1 and 99),
  created_at timestamptz not null default now(),
  unique (cart_id, product_id)
);
create index if not exists cart_items_cart_id_idx on public.cart_items (cart_id);

-- 3) 보안: 브라우저(anon 키)가 직접 읽고 쓰지 못하게 막고, 서버(secret 키)만 접근
alter table public.products enable row level security;
alter table public.cart_items enable row level security;

